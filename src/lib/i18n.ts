export type MessageKey = keyof typeof en;

const tables: Record<Locale, Record<MessageKey, string>> = { en, vi };

export function isLocale(value: unknown): value is Locale {
  return value === "en" || value === "vi";
}

export function translate(
  locale: Locale,
  key: MessageKey,
  vars?: Vars,
): string {
  let text = tables[locale][key] ?? tables.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function translateError(locale: Locale, message: string): string {
  if (message in tables.en || message in tables.vi) {
    return translate(locale, message as MessageKey);
  }
  return message;
}
